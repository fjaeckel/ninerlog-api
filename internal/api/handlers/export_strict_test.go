func TestStrictExportPDFMarksCorrectionsAndAppendix(t *testing.T) {
	flights, sigs, strict := strictFixture(t)
	g := geometryFor("a4")

	cases := []struct {
		name   string
		render func() *fpdf.Fpdf
	}{
		{"easa spread", func() *fpdf.Fpdf {
			return renderEASAWith(flights, g, nil, "Test Pilot", layoutSpread, nil, sigs, strict)
		}},
		{"easa single", func() *fpdf.Fpdf {
			return renderEASAWith(flights, g, nil, "Test Pilot", layoutSingle, nil, sigs, strict)
		}},
		{"faa spread", func() *fpdf.Fpdf {
			return generateFAAPDFWith(flights, g, "Test Pilot", layoutSpread, nil, sigs, strict)
		}},
		{"faa single", func() *fpdf.Fpdf {
			return generateFAAPDFWith(flights, g, "Test Pilot", layoutSingle, nil, sigs, strict)
		}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			text := string(renderedBytes(t, c.render()))
			mustContain(t, text, "\x861")
			mustContain(t, text, "\x862")
			mustNotContain(t, text, "\x863")
			for _, want := range []string{
				"History recorded since", "Logbook History", "Change Log", "Voided Entries",
				"wrong landing count", "1:30 -> 1:45", "D-GONE", "System: recalculation",
				"0123456789ab", "Signature Hashes", "Licence",
			} {
				mustContain(t, text, want)
			}
			mustNotContain(t, text, "0123456789abc")
		})
	}
}

func TestStrictExportMarkerSurvivesTruncation(t *testing.T) {
	_, _, strict := strictFixture(t)
	var id uuid.UUID
	for k := range strict.refs {
		id = k
		break
	}
	marker := strict.marker(id)
	if marker == "" {
		t.Fatal("no marker")
	}

	for _, max := range []int{26, 38, 58, 64} {
		got := strict.remarks(id, strings.Repeat("x", 200), max)
		if n := len([]rune(got)); n > max {
			t.Errorf("max %d: %d runes", max, n)
		}
		if !strings.HasSuffix(got, marker) {
			t.Errorf("max %d: marker lost in %q", max, got)
		}
	}
	mustEqual(t, marker, strict.remarks(id, "", 38))
	mustEqual(t, "short "+marker, strict.remarks(id, "short", 38))
	mustEqual(t, "short", strict.remarks(uuid.New(), "short", 38))
	mustEqual(t, "short", (*strictExport)(nil).remarks(id, "short", 38))
}

