func mustContain(t *testing.T, haystack, needle string) {
	t.Helper()
	if !strings.Contains(haystack, needle) {
		t.Errorf("output does not contain %q", needle)
	}
}

func mustNotContain(t *testing.T, haystack, needle string) {
	t.Helper()
	if strings.Contains(haystack, needle) {
		t.Errorf("output contains %q", needle)
	}
}

func mustEqual(t *testing.T, want, got any) {
	t.Helper()
	if !reflect.DeepEqual(want, got) {
		t.Errorf("want %v, got %v", want, got)
	}
}

var strictFixedTime = time.Date(2026, 6, 1, 8, 30, 0, 0, time.UTC)

var footerStamp = regexp.MustCompile(`Generated by NinerLog [^)]*?UTC`)

var contentStream = regexp.MustCompile(`(?s)<<([^<>]*?)>>\nstream\n(.*?)\nendstream`)

// pageStreams returns the uncompressed page content streams of doc with the
// footer timestamp removed. Image objects are left out: fpdf emits them in
// map order.
func pageStreams(t *testing.T, doc *fpdf.Fpdf) [][]byte {
	t.Helper()
	var out [][]byte
	for _, m := range contentStream.FindAllSubmatch(renderedBytes(t, doc), -1) {
		if bytes.Contains(m[1], []byte("FlateDecode")) {
			continue
		}
		out = append(out, footerStamp.ReplaceAll(m[2], []byte("Generated")))
	}
	return out
}

