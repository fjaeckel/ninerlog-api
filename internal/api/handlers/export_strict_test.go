func TestStandardExportPDFCarriesNoAuditTrail(t *testing.T) {
	flights, sigs, _ := strictFixture(t)
	hash := "0123456789abcdef"
	sigs[flights[2].ID].SignedFieldsHash = &hash
	g := geometryFor("a4")

	cases := []struct {
		name         string
		plain, withN func() *fpdf.Fpdf
	}{
		{"easa spread",
			func() *fpdf.Fpdf { return renderEASA(flights, g, nil, "Test Pilot", layoutSpread, nil, sigs) },
			func() *fpdf.Fpdf {
				return renderEASAWith(flights, g, nil, "Test Pilot", layoutSpread, nil, sigs, nil)
			}},
		{"faa single",
			func() *fpdf.Fpdf { return generateFAAPDF(flights, g, "Test Pilot", layoutSingle, nil, sigs) },
			func() *fpdf.Fpdf {
				return generateFAAPDFWith(flights, g, "Test Pilot", layoutSingle, nil, sigs, nil)
			}},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			plain := pageStreams(t, c.plain())
			if len(plain) == 0 {
				t.Fatal("no page streams")
			}
			mustEqual(t, plain, pageStreams(t, c.withN()))
			joined := string(bytes.Join(plain, nil))
			for _, banned := range []string{"\x86", "Change Log", "Voided Entries", "Logbook History", "History recorded", "Signature Hashes", "0123456789ab"} {
				mustNotContain(t, joined, banned)
			}
		})
	}
}

func TestStrictExportCSVColumns(t *testing.T) {
	flights := buildSamplePDFFlights(3)
	corrected := time.Date(2026, 5, 4, 10, 20, 30, 0, time.FixedZone("x", 3600))
	prefs := exportPrefs{DateFormat: "YYYY-MM-DD", DecimalSeparator: "dot"}
	marks := &csvCorrections{lastCorrectedAt: map[uuid.UUID]time.Time{flights[1].ID: corrected}, prefs: prefs}

	write := map[string]func(w *csv.Writer, m *csvCorrections){
		"standard": func(w *csv.Writer, m *csvCorrections) { writeStandardCSVWith(w, flights, prefs, nil, m) },
		"easa":     func(w *csv.Writer, m *csvCorrections) { writeEASACSVWith(w, flights, prefs, "Pilot", m) },
		"faa":      func(w *csv.Writer, m *csvCorrections) { writeFAACSVWith(w, flights, prefs, m) },
	}
	plainWriters := map[string]func(w *csv.Writer){
		"standard": func(w *csv.Writer) { writeStandardCSV(w, flights, prefs, nil) },
		"easa":     func(w *csv.Writer) { writeEASACSV(w, flights, prefs, "Pilot") },
		"faa":      func(w *csv.Writer) { writeFAACSV(w, flights, prefs) },
	}
	read := func(fn func(w *csv.Writer)) [][]string {
		var buf bytes.Buffer
		w := csv.NewWriter(&buf)
		fn(w)
		w.Flush()
		rows, err := csv.NewReader(&buf).ReadAll()
		if err != nil {
			t.Fatal(err)
		}
		return rows
	}

	for name, fn := range write {
		t.Run(name, func(t *testing.T) {
			standard := read(plainWriters[name])
			mustEqual(t, standard, read(func(w *csv.Writer) { fn(w, nil) }))
			for _, col := range standard[0] {
				if col == "corrected" || col == "last_corrected_at" {
					t.Errorf("standard header has %q", col)
				}
			}

			strict := read(func(w *csv.Writer) { fn(w, marks) })
			if len(strict) != len(standard) {
				t.Fatalf("rows = %d, want %d", len(strict), len(standard))
			}
			width := len(standard[0])
			mustEqual(t, append(append([]string{}, standard[0]...), "corrected", "last_corrected_at"), strict[0])
			for i := 1; i < len(strict); i++ {
				mustEqual(t, standard[i], strict[i][:width])
			}
			mustEqual(t, []string{"false", ""}, strict[1][width:])
			mustEqual(t, []string{"true", "2026-05-04 09:20"}, strict[2][width:])
			mustEqual(t, []string{"false", ""}, strict[3][width:])
		})
	}

	t.Run("last_corrected_at follows the user's date format", func(t *testing.T) {
		for format, want := range map[string]string{
			"DD.MM.YYYY": "04.05.2026 09:20", "MM/DD/YYYY": "05/04/2026 09:20", "YYYY-MM-DD": "2026-05-04 09:20",
		} {
			m := &csvCorrections{
				lastCorrectedAt: map[uuid.UUID]time.Time{flights[0].ID: corrected},
				prefs:           exportPrefs{DateFormat: format},
			}
			mustEqual(t, []string{"true", want}, m.row(nil, flights[0]))
		}
	})

	t.Run("totals row keeps the column count", func(t *testing.T) {
		mustEqual(t, 3, len(marks.totals([]string{"a"})))
		mustEqual(t, 1, len((*csvCorrections)(nil).totals([]string{"a"})))
	})
}

